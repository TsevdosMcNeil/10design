#!/usr/bin/env python3
"""
deploy.py - Deploy the 10design Statamic app from the local Docker setup to a
production server (no Docker) over SSH.

What it does:
  1. Pre-flight checks (local tools, git state, SSH access, remote app folder)
  2. Builds front-end assets locally (npm ci && npm run build in the node container)
  3. Shows a preview of the file changes and asks for confirmation
  4. Backs up the current production code on the server
  5. Syncs code with rsync - production-owned data (content, users, uploaded
     assets, storage, .env) is NEVER uploaded or deleted
  6. Runs composer install --no-dev and refreshes Laravel/Statamic caches remotely
  7. Checks the site responds

Usage:
  python3 deploy.py                    # deploy to [production]
  python3 deploy.py --dry-run          # preview only, changes nothing
  python3 deploy.py --list-backups
  python3 deploy.py --rollback         # restore the most recent backup
  python3 deploy.py --help             # all options

Configuration lives in deploy.ini (see deploy.ini.example). Standard library only.
"""

import argparse
import configparser
import datetime
import getpass
import os
import shlex
import shutil
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent

# Paths (relative to the Statamic app root) that are never uploaded and never
# deleted on the server. They belong to production: content edited in the
# Control Panel, uploads, runtime files and server-specific config.
PROTECTED_PATHS = [
    "/.env",
    "/.env.*",
    "/auth.json",
    "/.deployed",             # written on the server by this script
    "/.git/",
    "/node_modules/",
    "/vendor/",               # installed on the server by composer
    "/storage/",              # logs, sessions, stache, form submissions, glide cache
    "/bootstrap/cache/*.php", # generated by artisan optimize on the server
    "/content/",              # entries, globals, navigation, trees (Control Panel)
    "/users/",                # user accounts (Control Panel)
    "/resources/users/",      # roles and groups (Control Panel)
    "/resources/forms/",      # form definitions (Control Panel)
    "/public/assets/",        # uploaded asset container
    "/public/img/",           # Glide image cache
    "/public/static/",        # static cache
    "/public/storage",        # storage symlink
    "/public/vendor/",        # published by statamic:install on the server
    "/public/hot",            # Vite dev-server marker - must never reach production
    "/public/.user.ini",
    "/public/.well-known/",
    ".DS_Store",
]

# Folders left out of the pre-deploy backup: either never touched by a deploy
# (content, uploads) or rebuilt by the deploy itself (vendor).
BACKUP_EXCLUDES = [
    "./vendor", "./node_modules", "./storage", "./.git",
    "./content", "./users", "./public/assets", "./public/img",
    "./public/static", "./public/vendor",
]

CONTROL_PATH = os.path.expanduser("~/.ssh/cm-deploy-%C")


# --------------------------------------------------------------------------- output

def _c(code, text):
    return f"\033[{code}m{text}\033[0m" if sys.stdout.isatty() else text

def step(msg):  print("\n" + _c("1;34", f"==> {msg}"))
def info(msg):  print(f"    {msg}")
def ok(msg):    print(_c("32", f"    ✔ {msg}"))
def warn(msg):  print(_c("33", f"    ! {msg}"))

def fail(msg, code=1):
    print(_c("31", f"\n✖ {msg}"), file=sys.stderr)
    sys.exit(code)

def confirm(question, assume_yes):
    if assume_yes:
        return True
    answer = input(_c("1", f"\n{question} [y/N] ")).strip().lower()
    return answer in ("y", "yes")


# --------------------------------------------------------------------------- config

class Config:
    def __init__(self, path, env):
        parser = configparser.ConfigParser(interpolation=None)
        if not parser.read(path):
            fail(f"Config file not found: {path}\n  Copy deploy.ini.example to deploy.ini and fill it in.")
        if env not in parser:
            fail(f"Environment [{env}] not found in {path}. Available: {', '.join(parser.sections())}")
        s = parser[env]

        def need(key):
            value = s.get(key, "").strip()
            if not value:
                fail(f"Missing required setting '{key}' in [{env}] of {path}")
            return value

        self.env = env
        # host can be a Host alias from ~/.ssh/config; user and port are optional
        # and, when empty, come from that config (or ssh's defaults).
        self.host = need("host")
        self.user = s.get("user", "").strip()
        self.path = need("path").rstrip("/")
        self.port = s.get("port", "").strip()
        self.ssh_key = os.path.expanduser(s.get("ssh_key", "").strip())
        self.site_url = s.get("site_url", "").strip()
        self.php = s.get("php", "php").strip()
        self.composer = s.get("composer", "composer").strip()
        self.backup_dir = s.get("backup_dir", "~/deploy-backups").strip().rstrip("/")
        self.keep_backups = s.getint("keep_backups", 5)
        self.reload_command = s.get("reload_command", "").strip()
        self.maintenance = s.getboolean("maintenance", False)
        self.clear_static_cache = s.getboolean("clear_static_cache", True)
        self.rsync_chmod = s.get("rsync_chmod", "D755,F644").strip()
        self.local_path = (SCRIPT_DIR / s.get("local_path", "statamic").strip()).resolve()
        self.build_command = s.get(
            "build_command", 'docker compose exec -T node sh -c "npm ci && npm run build"'
        ).strip()
        self.extra_excludes = [
            line.strip() for line in s.get("extra_excludes", "").splitlines() if line.strip()
        ]
        # Exceptions to the excludes, e.g. /public/build/ when /public/* is excluded
        self.extra_includes = [
            line.strip() for line in s.get("extra_includes", "").splitlines() if line.strip()
        ]

    @property
    def target(self):
        return f"{self.user}@{self.host}" if self.user else self.host

    @property
    def excludes(self):
        return PROTECTED_PATHS + self.extra_excludes


# --------------------------------------------------------------------------- ssh / shell

def ssh_cmd(cfg):
    cmd = ["ssh"]
    if cfg.port:
        cmd += ["-p", cfg.port]
    cmd += ["-o", "ControlMaster=auto",
           "-o", f"ControlPath={CONTROL_PATH}",
           "-o", "ControlPersist=120"]
    if cfg.ssh_key:
        cmd += ["-i", cfg.ssh_key]
    return cmd

def remote(cfg, script, capture=False, check=True):
    """Run a bash script on the server (fed through stdin, so no quoting issues)."""
    full = "set -euo pipefail\n" + script
    result = subprocess.run(
        ssh_cmd(cfg) + [cfg.target, "bash", "-s"],
        input=full, text=True,
        stdout=subprocess.PIPE if capture else None,
        stderr=subprocess.STDOUT if capture else None,
    )
    if check and result.returncode != 0:
        if capture and result.stdout:
            print(result.stdout)
        fail(f"Remote command failed (exit {result.returncode}).")
    return result

def local(cmd, cwd=None, capture=False):
    return subprocess.run(cmd, cwd=cwd, text=True,
                          stdout=subprocess.PIPE if capture else None,
                          stderr=subprocess.PIPE if capture else None)

def git(cfg, *args):
    r = local(["git", "-C", str(cfg.local_path), *args], capture=True)
    return r.stdout.strip() if r.returncode == 0 else None


# --------------------------------------------------------------------------- steps

def preflight_local(cfg, allow_dirty):
    step("Local checks")
    for tool in ("ssh", "rsync"):
        if not shutil.which(tool):
            fail(f"'{tool}' is not installed locally.")
    r = local(["rsync", "--version"], capture=True)
    version = ((r.stdout or "") + (r.stderr or "")).strip().splitlines()[0]
    if is_openrsync():
        info(f"Using macOS {version.strip()} (rsync_chmod is skipped; reload_command sets permissions)")
    elif "version 2." in version:
        warn(f"Old rsync detected ({version.strip()}). Recommended: a rsync 3.x")
    else:
        ok(version.strip())

    if not (cfg.local_path / "artisan").is_file():
        fail(f"No Laravel app found at {cfg.local_path} (missing artisan). Check local_path.")
    if not (cfg.local_path / "composer.lock").is_file():
        fail("composer.lock is missing - the server would resolve different package versions.")
    ok(f"App folder: {cfg.local_path}")

    rev = git(cfg, "rev-parse", "--short", "HEAD")
    if rev is None:
        warn("Not a git repository - can't check for uncommitted changes.")
        return {"rev": "no-git", "branch": "-"}
    branch = git(cfg, "rev-parse", "--abbrev-ref", "HEAD")
    dirty = git(cfg, "status", "--porcelain")
    if dirty:
        print(dirty)
        if not allow_dirty:
            fail("Uncommitted changes (listed above). Commit them first, or use --allow-dirty.")
        warn("Deploying with uncommitted changes (--allow-dirty).")
        rev += "-dirty"
    ok(f"Git: {branch} @ {rev}")
    return {"rev": rev, "branch": branch}

def preflight_remote(cfg):
    step(f"Remote checks ({cfg.target}:{cfg.path})")
    p = shlex.quote(cfg.path)
    r = remote(cfg, f"""
test -d {p} || {{ echo "MISSING_DIR"; exit 0; }}
test -f {p}/artisan || {{ echo "MISSING_ARTISAN"; exit 0; }}
test -f {p}/.env || echo "MISSING_ENV"
command -v rsync >/dev/null || echo "MISSING_RSYNC"
command -v {shlex.quote(cfg.composer)} >/dev/null || echo "MISSING_COMPOSER"
{shlex.quote(cfg.php)} -r 'echo "PHP ".PHP_VERSION.PHP_EOL;'
""", capture=True)
    out = r.stdout or ""
    checks = {
        "MISSING_DIR": f"Remote folder {cfg.path} does not exist.",
        "MISSING_ARTISAN": f"No Laravel app at {cfg.path} (artisan not found).",
        "MISSING_ENV": f"No .env in {cfg.path} - create it on the server first (it is never uploaded).",
        "MISSING_RSYNC": "rsync is not installed on the server.",
        "MISSING_COMPOSER": f"'{cfg.composer}' not found on the server. Set 'composer' in deploy.ini.",
    }
    for marker, message in checks.items():
        if marker in out:
            fail(message)
    ok("SSH connection works")
    for line in out.splitlines():
        if line.startswith("PHP "):
            ok(f"Server {line}")

def build_assets(cfg):
    step("Building front-end assets locally")
    info(cfg.build_command)
    if subprocess.run(cfg.build_command, shell=True, cwd=SCRIPT_DIR).returncode != 0:
        fail("Asset build failed. Is the Docker stack running? (docker compose up -d)")
    check_build(cfg)

def check_build(cfg):
    if (cfg.local_path / "public" / "hot").exists():
        warn("public/hot exists locally (Vite dev server running). It is excluded from the upload.")
    manifest = cfg.local_path / "public" / "build" / "manifest.json"
    if not manifest.is_file():
        fail("public/build/manifest.json not found - assets are not built.")
    age = datetime.datetime.now() - datetime.datetime.fromtimestamp(manifest.stat().st_mtime)
    ok(f"Build manifest found ({int(age.total_seconds() // 60)} min old)")

_OPENRSYNC = None

def is_openrsync():
    """macOS ships openrsync, which lacks some GNU rsync options (e.g. --chmod=D755,F644)."""
    global _OPENRSYNC
    if _OPENRSYNC is None:
        r = local(["rsync", "--version"], capture=True)
        _OPENRSYNC = "openrsync" in (r.stdout or "") + (r.stderr or "")
    return _OPENRSYNC

def rsync_cmd(cfg, dry_run, delete):
    # --checksum: compare file contents, not size+mtime. A fresh clone gives every
    # file a new mtime, and same-size edits could otherwise be skipped.
    cmd = ["rsync", "-rltz", "--checksum", "--itemize-changes", "--stats",
           "-e", " ".join(shlex.quote(x) for x in ssh_cmd(cfg))]
    if not is_openrsync():
        cmd.append("--human-readable")
        if cfg.rsync_chmod:
            cmd.append(f"--chmod={cfg.rsync_chmod}")
    if dry_run:
        cmd.append("--dry-run")
    if delete:
        cmd.append("--delete")  # excluded (protected) paths are still never deleted
    # rsync uses the first rule that matches, so the protected paths go first
    # (they can never be re-included), then the includes, then the extra excludes.
    for pattern in PROTECTED_PATHS:
        cmd += ["--exclude", pattern]
    for pattern in cfg.extra_includes:
        cmd += ["--include", pattern]
    for pattern in cfg.extra_excludes:
        cmd += ["--exclude", pattern]
    cmd += [f"{cfg.local_path}/", f"{cfg.target}:{cfg.path}/"]
    return cmd

def preview(cfg, delete):
    step("Previewing changes (rsync --dry-run)")
    r = local(rsync_cmd(cfg, dry_run=True, delete=delete), capture=True)
    if r.returncode != 0:
        print(r.stderr)
        fail("rsync preview failed.")
    changes = [l for l in r.stdout.splitlines()
               if l.startswith(("<f", "cd", "*deleting", ">f", "cL", "<L"))]
    uploads = [l for l in changes if l.startswith(("<f", "<L"))]
    deletes = [l for l in changes if l.startswith("*deleting")]
    for line in changes[:300]:
        print("    " + line)
    if len(changes) > 300:
        info(f"... and {len(changes) - 300} more")
    info(f"{len(uploads)} file(s) to upload, {len(deletes)} to delete")
    if deletes:
        warn("Files will be DELETED on the server (lines marked *deleting).")
    return len(uploads) + len(deletes)

def backup(cfg, meta):
    step("Backing up current production code")
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    name = f"{Path(cfg.path).name}-{stamp}-{meta['rev']}.tar.gz"
    excludes = " ".join(f"--exclude={shlex.quote(e)}" for e in BACKUP_EXCLUDES)
    bdir = backup_dir_expr(cfg)
    r = remote(cfg, f"""
mkdir -p {bdir}
tar {excludes} -czf {bdir}/{shlex.quote(name)} -C {shlex.quote(cfg.path)} .
ls -1t {bdir}/*.tar.gz | tail -n +{cfg.keep_backups + 1} | xargs -r rm -f
du -h {bdir}/{shlex.quote(name)} | cut -f1
""", capture=True)
    size = (r.stdout or "").strip().splitlines()[-1:] or ["?"]
    ok(f"{cfg.backup_dir}/{name} ({size[0]}, keeping the last {cfg.keep_backups})")
    return name

def sync(cfg, delete):
    step("Uploading code (rsync)")
    r = local(rsync_cmd(cfg, dry_run=False, delete=delete), capture=True)
    if r.returncode != 0:
        print(r.stderr)
        fail("rsync failed. The backup is untouched - run --rollback if the site is broken.")
    for line in r.stdout.splitlines():
        if line.startswith(("Number of regular files transferred", "Total transferred file size")):
            info(line.strip())
    ok("Code uploaded")

def post_deploy(cfg, meta, search):
    step("Running post-deploy commands on the server")
    php, composer = shlex.quote(cfg.php), shlex.quote(cfg.composer)
    lines = [f"cd {shlex.quote(cfg.path)}"]
    if cfg.maintenance:
        # the trap brings the site back up even if a later command fails
        lines += [f'trap "{php} artisan up" EXIT', f"{php} artisan down --retry=15"]
    lines += [
        "rm -f public/hot",
        f"{composer} install --no-dev --prefer-dist --optimize-autoloader --no-interaction",
        f"{php} artisan optimize:clear",
        f"{php} artisan optimize",
        f"{php} please stache:warm",
    ]
    if cfg.clear_static_cache:
        lines.append(f"{php} please static:clear")
    if search:
        lines.append(f"{php} please search:update --all")
    if cfg.reload_command:
        lines.append(cfg.reload_command)
    stamp = datetime.datetime.now().isoformat(timespec="seconds")
    record = [
        "revision=" + meta["rev"],
        "branch=" + meta["branch"],
        "deployed_at=" + stamp,
        "deployed_by=" + getpass.getuser(),
    ]
    script = []
    for l in lines:
        if not l.startswith(("trap ", "cd ")):
            script.append("printf '    $ %s\\n' " + shlex.quote(l))  # echo each command before running it
        script.append(l)
    script.append("printf '%s\\n' " + " ".join(shlex.quote(x) for x in record) + " > .deployed")
    remote(cfg, "\n".join(script))
    if not cfg.reload_command:
        warn("No reload_command set: if opcache.validate_timestamps=0 on the server, "
             "PHP may keep serving old code until PHP-FPM is reloaded.")
    ok("Post-deploy commands finished")

def health_check(cfg):
    if not cfg.site_url:
        return True
    step(f"Health check: {cfg.site_url}")
    req = urllib.request.Request(cfg.site_url, headers={"User-Agent": "deploy.py health check"})
    try:
        with urllib.request.urlopen(req, timeout=20) as resp:
            ok(f"HTTP {resp.status}")
            return True
    except urllib.error.HTTPError as e:
        warn(f"HTTP {e.code} - the site is responding with an error.")
    except Exception as e:  # noqa: BLE001
        warn(f"Request failed: {e}")
    return False


# --------------------------------------------------------------------------- backups

def backup_dir_expr(cfg):
    """Shell-safe expression for the backup folder; a leading ~ expands to the remote $HOME."""
    d = cfg.backup_dir
    if d == "~":
        return '"$HOME"'
    if d.startswith("~/"):
        return '"$HOME"/' + shlex.quote(d[2:])
    return shlex.quote(d)

def list_backups(cfg):
    r = remote(cfg, f"ls -1t {backup_dir_expr(cfg)}/*.tar.gz 2>/dev/null | xargs -r -n1 basename || true",
               capture=True)
    return [l for l in (r.stdout or "").splitlines() if l.endswith(".tar.gz")]

def rollback(cfg, name, assume_yes, search):
    backups = list_backups(cfg)
    if not backups:
        fail(f"No backups found in {cfg.backup_dir} on the server.")
    name = name or backups[0]
    if name not in backups:
        fail(f"Backup '{name}' not found. Use --list-backups.")
    step(f"Rollback to {name}")
    info("Restores code files from the backup. Files added since then are not removed.")
    if not confirm(f"Restore {name} on {cfg.target}:{cfg.path}?", assume_yes):
        fail("Cancelled.", 0)
    remote(cfg, f"tar -xzf {backup_dir_expr(cfg)}/{shlex.quote(name)} -C {shlex.quote(cfg.path)}")
    ok("Files restored")
    post_deploy(cfg, {"rev": f"rollback:{name}", "branch": "-"}, search)
    health_check(cfg)


# --------------------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser(description="Deploy the Statamic app to the server over SSH.")
    ap.add_argument("--env", default="production", help="section of deploy.ini to use (default: production)")
    ap.add_argument("--config", default=str(SCRIPT_DIR / "deploy.ini"), help="path to deploy.ini")
    ap.add_argument("--dry-run", action="store_true", help="checks + change preview only; nothing is built or changed")
    ap.add_argument("-y", "--yes", action="store_true", help="don't ask for confirmation")
    ap.add_argument("--skip-build", action="store_true", help="upload the existing public/build without rebuilding")
    ap.add_argument("--skip-backup", action="store_true", help="don't back up production before syncing")
    ap.add_argument("--delete", action="store_true",
                    help="delete server files that no longer exist locally (protected paths are never deleted)")
    ap.add_argument("--search", action="store_true", help="rebuild search indexes after deploying")
    ap.add_argument("--allow-dirty", action="store_true", help="allow uncommitted local changes")
    ap.add_argument("--list-backups", action="store_true", help="list backups on the server")
    ap.add_argument("--rollback", nargs="?", const="", metavar="BACKUP",
                    help="restore a backup (latest if no name given)")
    args = ap.parse_args()

    cfg = Config(args.config, args.env)
    print(_c("1", f"Statamic deploy → [{cfg.env}] {cfg.target}:{cfg.path}"))

    if args.list_backups:
        step(f"Backups in {cfg.backup_dir}")
        for b in list_backups(cfg) or ["(none)"]:
            info(b)
        return

    if args.rollback is not None:
        preflight_remote(cfg)
        rollback(cfg, args.rollback or None, args.yes, args.search)
        return

    meta = preflight_local(cfg, args.allow_dirty)
    preflight_remote(cfg)

    if args.dry_run:
        check_build(cfg)
        preview(cfg, args.delete)
        print(_c("1", "\nDry run finished - nothing was changed."))
        return

    if args.skip_build:
        step("Skipping asset build (--skip-build)")
        check_build(cfg)
    else:
        build_assets(cfg)

    changes = preview(cfg, args.delete)
    if changes == 0:
        info("No file changes. Post-deploy commands will still run (caches, composer).")
    if not confirm(f"Deploy {meta['rev']} to {cfg.env}?", args.yes):
        fail("Cancelled - nothing was changed on the server.", 0)

    backup_name = None if args.skip_backup else backup(cfg, meta)
    sync(cfg, args.delete)
    post_deploy(cfg, meta, args.search)
    healthy = health_check(cfg)

    print()
    if healthy:
        print(_c("1;32", f"✔ Deployed {meta['rev']} to {cfg.env}"))
    else:
        print(_c("1;33", f"! Deployed {meta['rev']} to {cfg.env}, but the health check failed"))
    if backup_name:
        info(f"Roll back with: python3 deploy.py --env {cfg.env} --rollback {backup_name}")


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        fail("Interrupted.", 130)
